/// Draw a single 8x16 character at pixel position (x, y).
pub fn draw_char_16(x: u32, y: u32, c: char, color: u32) {
    let idx = (c as usize).min(127);
    let glyph = &FONT_8X16[idx];
    unsafe {
        let fb = core::ptr::addr_of_mut!(FRAMEBUFFER) as *mut u32;
        let mut row = 0u32;
        while row < 16 {
            let py = y + row;
            if (py as usize) >= HEIGHT { break; }
            let bits = glyph[row as usize];
            let mut bit = 0u32;
            while bit < 8 {
                let px = x + bit;
                if (px as usize) < WIDTH && (bits >> bit) & 1 != 0 {
                    core::ptr::write_volatile(
                        fb.add(py as usize * WIDTH + px as usize), color);
                }
                bit += 1;
            }
            row += 1;
        }
    }
}

/// Draw a string with 8x16 font. Char spacing = 9px.
pub fn draw_str_16(x: u32, y: u32, s: &str, color: u32) {
    let mut cx = x;
    for c in s.chars() {
        if (cx as usize) + 8 >= WIDTH { break; }
        draw_char_16(cx, y, c, color);
        cx += 9;
    }
}

/// Draw a string with 8x16 font, clipped at max_x.
pub fn draw_str_16_clipped(x: u32, y: u32, s: &str, color: u32, max_x: u32) {
    let mut cx = x;
    for c in s.chars() {
        if cx + 8 > max_x { break; }
        draw_char_16(cx, y, c, color);
        cx += 9;
    }
}