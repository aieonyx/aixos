pub fn blit(dst_x: u32, dst_y: u32) {
    use crate::framebuffer::{FRAMEBUFFER, WIDTH};
    unsafe {
        let fb = core::ptr::addr_of_mut!(FRAMEBUFFER) as *mut u32;
        let mut si = 0usize;
        let mut sy = 0u32;
        while sy < H {
            let mut sx = 0u32;
            while sx < W {
                let pixel = PIXELS[si];
                let alpha = (pixel >> 24) & 0xFF;
                if alpha > 8 {
                    let offset = (dst_y + sy) as usize * WIDTH + (dst_x + sx) as usize;
                    if alpha >= 250 {
                        core::ptr::write_volatile(fb.add(offset), pixel & 0x00FFFFFF);
                    } else {
                        let bg = core::ptr::read_volatile(fb.add(offset));
                        let a = alpha;
                        let ia = 255 - a;
                        let r = ((((pixel>>16)&0xFF)*a + ((bg>>16)&0xFF)*ia) / 255) & 0xFF;
                        let g = ((((pixel>>8)&0xFF)*a  + ((bg>>8)&0xFF)*ia)  / 255) & 0xFF;
                        let b = (((pixel&0xFF)*a       + (bg&0xFF)*ia)        / 255) & 0xFF;
                        core::ptr::write_volatile(fb.add(offset), (r<<16)|(g<<8)|b);
                    }
                }
                si += 1;
                sx += 1;
            }
            sy += 1;
        }
    }
}